async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('http://127.0.0.1:8765/');
  await page.waitForSelector('.node');
  check(await page.locator('.node').count() === 39, 'Expected 39 map nodes');
  await page.locator('[data-field="SWE"]').click();
  await page.locator('#list-mode').click();
  check(await page.locator('.result-card').count() === 11, 'SWE filter');
  await page.locator('[data-id="SWE-01"].result-card').click();
  await page.waitForSelector('#detail-title');
  check(await page.locator('#detail section h3').count() === 7, 'Six sections plus sources');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('a[href^="/api/assets/"]').first().click();
  const download = await downloadPromise;
  check(!!download.suggestedFilename(), 'Saved source download');
  await page.locator('[data-related="SWE-02"]').click();
  await page.waitForFunction(() => document.querySelector('#detail-label').textContent.endsWith('SWE-02'));
  await page.keyboard.press('Escape');
  check(await page.locator('#detail').isHidden(), 'Escape closes detail');
  await page.locator('#clear').click();
  await page.locator('#search').fill('zzzznomatch');
  check(await page.locator('#empty').isVisible(), 'No-results state');
  await page.locator('#empty-reset').click();
  check(await page.locator('.result-card').count() === 39, 'Reset filters');
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await page.waitForSelector('.result-card');
  check(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Mobile horizontal overflow');
  await page.locator('#search').fill('quantum');
  check(await page.locator('.result-card').count() > 0, 'Full text search');
  await page.goto('http://127.0.0.1:8765/#ROB-01');
  await page.waitForSelector('#detail-title');
  check((await page.locator('#detail-title').innerText()).includes('physical work'), 'Hash navigation');
  await page.screenshot({path:'/tmp/atlas-mobile-verified.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  check(errors.length === 0, errors.join('\n'));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('http://127.0.0.1:8765/');
  await page.reload();
  await page.waitForSelector('.node');
  await page.screenshot({path:'/tmp/atlas-overview-verified.png',fullPage:true,animations:'disabled'});
  return {passed:true,breakthroughs:39,fields:4,checks:['filters','search','empty state','details','related navigation','source download','deep link','mobile layout','Escape','no JS errors']};
}
